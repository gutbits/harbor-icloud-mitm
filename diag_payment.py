from playwright.sync_api import sync_playwright

p = sync_playwright().start()
b = p.chromium.launch(channel='chrome', headless=True)
pg = b.new_page(viewport={'width': 1000, 'height': 940})
pg.goto('http://127.0.0.1:8099/payment.html', wait_until='networkidle', timeout=30000)
print('title:', pg.title())
print('h1:', pg.locator('#payment-title').inner_text())
print('lede:', pg.locator('.trust-browser__lede').inner_text()[:70])
btn = pg.locator('#payment-continue')
print('continue btn:', btn.inner_text(), '| visible:', btn.is_visible())
card = pg.locator('.trust-card')
print('card visible:', card.is_visible())
print('card bg:', pg.evaluate("() => getComputedStyle(document.querySelector('.trust-card')).backgroundColor"))
print('card radius:', pg.evaluate("() => getComputedStyle(document.querySelector('.trust-card')).borderRadius"))
print('payment icon visible:', pg.locator('svg.signin-logo').is_visible())
pg.screenshot(path='../mirror/payment_check.png')
b.close()
p.stop()
print('done')