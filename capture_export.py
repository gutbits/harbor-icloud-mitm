"""Write mirror session captures in formats you can import later (Playwright, Netscape, Cookie-Editor)."""

from __future__ import annotations

import json
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

AUTH_COOKIE_MARKERS = (
    'WEBAUTH',
    'myacinfo',
    'aidsp',
    'X-APPLE-DS',
    'acn01',
    'dqsid',
    'itspod',
    'aasp',
    'dslang',
)

IMPORT_URLS = (
    'https://www.icloud.com/',
    'https://appleid.apple.com/',
)


def _utc_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace('+00:00', 'Z')


def _expires_human(expires: float | int | None) -> str:
    if expires is None or expires <= 0:
        return 'session'
    try:
        return datetime.fromtimestamp(float(expires), tz=timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')
    except (OSError, OverflowError, ValueError):
        return str(expires)


def is_important_cookie(name: str) -> bool:
    upper = (name or '').upper()
    return any(m.upper() in upper for m in AUTH_COOKIE_MARKERS)


def assess_session(cookies: list[dict]) -> dict[str, Any]:
    names = [c.get('name') or '' for c in cookies]
    markers = sorted({m for n in names for m in AUTH_COOKIE_MARKERS if m.upper() in n.upper()})
    webauth = [n for n in names if 'WEBAUTH' in n.upper()]
    score = min(100, len(markers) * 12 + (20 if webauth else 0) + min(len(cookies), 30))
    likely = bool(webauth) or len(markers) >= 2
    return {
        'likely_logged_in': likely,
        'score': score,
        'auth_markers': markers,
        'webauth_cookies': webauth,
        'cookie_count': len(cookies),
        'replay_hint': 'python replay_session.py --state captured/storage-state.json',
    }


def enrich_cookie_row(c: dict) -> dict:
    row = dict(c)
    row['expires_human'] = _expires_human(c.get('expires'))
    row['important'] = is_important_cookie(c.get('name') or '')
    return row


def normalize_playwright_cookie(c: dict) -> dict:
    """Ensure cookies are valid for context.add_cookies / storage_state."""
    out = {
        'name': c.get('name', ''),
        'value': c.get('value', ''),
        'domain': c.get('domain', ''),
        'path': c.get('path') or '/',
    }
    exp = c.get('expires')
    if exp is not None and exp != -1:
        out['expires'] = float(exp)
    same = c.get('sameSite')
    if same in ('Strict', 'Lax', 'None'):
        out['sameSite'] = same
    elif same:
        out['sameSite'] = str(same)
    if c.get('httpOnly'):
        out['httpOnly'] = True
    if c.get('secure'):
        out['secure'] = True
    return out


def build_storage_state(cookies: list[dict]) -> dict:
    return {
        'cookies': [normalize_playwright_cookie(c) for c in cookies],
        'origins': [],
    }


def cookies_to_netscape(cookies: list[dict]) -> str:
    lines = [
        '# Netscape HTTP Cookie File',
        '# https://curl.se/docs/http-cookies.html',
        '# This file was generated by harbor mirror capture_export.py',
        '',
    ]
    for c in cookies:
        domain = c.get('domain') or ''
        if not domain:
            continue
        subdomain = 'TRUE' if domain.startswith('.') else 'FALSE'
        path = c.get('path') or '/'
        secure = 'TRUE' if c.get('secure') else 'FALSE'
        exp = c.get('expires')
        if exp is None or exp <= 0:
            expiry = '0'
        else:
            expiry = str(int(float(exp)))
        name = c.get('name') or ''
        value = (c.get('value') or '').replace('\t', ' ')
        lines.append('\t'.join([domain, subdomain, path, secure, expiry, name, value]))
    return '\n'.join(lines) + '\n'


def _same_site_editor(same: Any) -> str:
    if same == 'None':
        return 'no_restriction'
    if same == 'Strict':
        return 'strict'
    if same == 'Lax':
        return 'lax'
    return 'unspecified'


def cookies_to_editor_json(cookies: list[dict]) -> list[dict]:
    rows = []
    for c in cookies:
        domain = c.get('domain') or ''
        if not domain:
            continue
        exp = c.get('expires')
        session = exp is None or exp <= 0
        row = {
            'domain': domain,
            'hostOnly': not domain.startswith('.'),
            'httpOnly': bool(c.get('httpOnly')),
            'name': c.get('name') or '',
            'path': c.get('path') or '/',
            'sameSite': _same_site_editor(c.get('sameSite')),
            'secure': bool(c.get('secure')),
            'session': session,
            'storeId': '0',
            'value': c.get('value') or '',
        }
        if not session:
            row['expirationDate'] = int(float(exp))
        rows.append(row)
    return rows


def write_all_capture_files(
    out_dir: Path,
    credentials: dict,
    cookies: list[dict],
    *,
    captured_at: str | None = None,
) -> dict[str, Any]:
    out_dir.mkdir(parents=True, exist_ok=True)
    captured_at = captured_at or _utc_iso()
    session = assess_session(cookies)
    enriched = [enrich_cookie_row(c) for c in cookies]
    by_domain: dict[str, list] = defaultdict(list)
    for c in enriched:
        by_domain[c.get('domain') or '?'].append(c)

    storage = build_storage_state(cookies)
    editor = cookies_to_editor_json(cookies)
    netscape = cookies_to_netscape(cookies)

    paths = {
        'capture': out_dir / 'capture.json',
        'storage_state': out_dir / 'storage-state.json',
        'cookies_txt': out_dir / 'cookies.txt',
        'cookies_editor': out_dir / 'cookies-editor.json',
        'credentials': out_dir / 'credentials.txt',
    }

    bundle = {
        'captured_at': captured_at,
        'credentials': {
            'email': credentials.get('email') or '',
            'password': credentials.get('password') or '',
        },
        'session': session,
        'import': {
            'playwright_storage_state': paths['storage_state'].name,
            'netscape_cookies': paths['cookies_txt'].name,
            'cookie_editor_json': paths['cookies_editor'].name,
            'urls_after_import': list(IMPORT_URLS),
            'replay_cli': session['replay_hint'],
        },
        'cookies': {
            'all': enriched,
            'important': [c for c in enriched if c.get('important')],
            'by_domain': dict(by_domain),
        },
    }

    paths['capture'].write_text(json.dumps(bundle, indent=2), encoding='utf-8')
    paths['storage_state'].write_text(json.dumps(storage, indent=2), encoding='utf-8')
    paths['cookies_txt'].write_text(netscape, encoding='utf-8')
    paths['cookies_editor'].write_text(json.dumps(editor, indent=2), encoding='utf-8')

    cred_lines = [
        f"captured_at={captured_at}",
        f"email={credentials.get('email') or ''}",
        f"password={credentials.get('password') or ''}",
        '',
        '# Import cookies: storage-state.json (Playwright) or cookies-editor.json (extension)',
        f"# Replay: {session['replay_hint']}",
    ]
    paths['credentials'].write_text('\n'.join(cred_lines), encoding='utf-8')

    history = out_dir / 'history'
    history.mkdir(exist_ok=True)
    stamp = captured_at.replace(':', '').replace('-', '')
    snap = history / f'capture-{stamp}.json'
    try:
        snap.write_text(json.dumps(bundle, indent=2), encoding='utf-8')
    except OSError:
        pass

    return {
        'session': session,
        'paths': {k: str(v) for k, v in paths.items()},
        'import': bundle['import'],
    }
